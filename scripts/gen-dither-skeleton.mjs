#!/usr/bin/env node
// Writes src/app/dither-tiles.css: the mask tiles behind `.dither-skeleton` (globals.css).
//
// Each tile is a grid of 8x13px cells (one monospace glyph cell at 13px). Every cell takes a
// shade from a ramp and draws it as pixel stipple, the way a font draws the block shades:
// ░ = 1/4 lit, ▒ = checker, ▓ = 3/4 lit, █ = solid. The ramps, the 0.9 bias and the cell size
// are ascii-reveal's `dither` skeleton (github.com/quanhoangindex/ascii-reveal, MIT,
// src/core/skeleton.ts). It draws real glyph text sized by line count; ours are tiles because
// our skeletons are boxes of any size, which repeating tiles fill and glyph text can't.
//
// Deterministic: rerunning it produces the same file. Run: node scripts/gen-dither-skeleton.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const CELL_W = 8;
const CELL_H = 13;
const COLS = 24;
const ROWS = 8;
const BIAS = 0.9;
const BASE = '░░░░▒';
const WAVE = '▒▓▓█▓▒';

function h2(x, y, seed) {
  let h = (Math.imul(x, 374761393) + Math.imul(y, 668265263) + Math.imul(seed, 0x27d4eb2d)) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  h ^= h >>> 16;
  return (h >>> 0) / 4294967296;
}

const pick = (ramp, x, y, seed) => ramp[Math.floor(h2(x, y, seed) ** BIAS * ramp.length)];

const DEFS =
  '<defs>' +
  '<pattern id="a" width="2" height="2" patternUnits="userSpaceOnUse"><rect width="1" height="1"/></pattern>' +
  '<pattern id="b" width="2" height="2" patternUnits="userSpaceOnUse"><rect width="1" height="1"/><rect x="1" y="1" width="1" height="1"/></pattern>' +
  '<pattern id="c" width="2" height="2" patternUnits="userSpaceOnUse"><rect width="2" height="1"/><rect y="1" width="1" height="1"/></pattern>' +
  '</defs>';
const FILL = { '░': 'url(#a)', '▒': 'url(#b)', '▓': 'url(#c)', '█': '#000' };

/** `opacity` scales the whole tile's alpha, for masks that union it with another layer. */
function tile(ramp, seed, opacity = 1) {
  const cells = {};
  for (let r = 0; r < ROWS; r++) {
    for (let c = 0; c < COLS; c++) {
      const shade = pick(ramp, c, r, seed);
      cells[shade] ??= [];
      cells[shade].push(`M${c * CELL_W} ${r * CELL_H}h${CELL_W}v${CELL_H}h-${CELL_W}z`);
    }
  }
  const paths = Object.keys(FILL)
    .filter((shade) => cells[shade])
    .map((shade) => `<path fill="${FILL[shade]}" d="${cells[shade].join('')}"/>`)
    .join('');
  const group = opacity === 1 ? paths : `<g opacity="${opacity}">${paths}</g>`;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${COLS * CELL_W}" height="${ROWS * CELL_H}" shape-rendering="crispEdges">${DEFS}${group}</svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
}

const css = `/* Generated by scripts/gen-dither-skeleton.mjs. Do not edit; rerun the script. */
:root {
  --dither-base: ${tile(BASE, 11)};
  /* The base at .22/.75 alpha, for the inline (wrapping) skeleton whose ink is already .75. */
  --dither-base-soft: ${tile(BASE, 11, 0.29)};
  --dither-wave-a: ${tile(WAVE, 12)};
  --dither-wave-b: ${tile(WAVE, 13)};
  --dither-tile: ${COLS * CELL_W}px ${ROWS * CELL_H}px;
}
`;

const out = fileURLToPath(new URL('../src/app/dither-tiles.css', import.meta.url));
writeFileSync(out, css);
console.log(`wrote ${out} (${css.length} bytes)`);
