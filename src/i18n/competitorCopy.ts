/** Translate controlled lifecycle/status codes; preserve unknown technical codes. */
export function competitorStateLabel(
  code: string,
  translate: ReturnType<typeof useTranslations<'competitor'>>,
): string {
  if (Object.hasOwn(stateSources, code))
    return localizeCompetitorCopy(stateSources[code as keyof typeof stateSources], translate);
  return /^[a-z][a-z0-9_]*$/.test(code) ? code : localizeCompetitorCopy('Unknown', translate);
}
